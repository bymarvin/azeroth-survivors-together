"""Game file patches: format, packing (our side) and streaming apply (players, stdlib only).

A patch turns one exact old file (SHA-256) into one exact new file. It is the
bsdiff algorithm (generated by patchgen/azpatch-gen) with its three streams
compressed by lzma (xz):

  AZP1 container: <4s b'AZP1'><Q new size><Q ctrl xz bytes><Q diff xz bytes><Q extra xz bytes>
                  ctrl xz, diff xz, extra xz
  ctrl:  (add_len, extra_len, seek) little-endian i64 triples
  diff:  new - old byte-wise (wrapping) for every add run
  extra: new bytes without an old counterpart

A full asset is the plain xz of the new file. Apply streams in 1 MiB pieces:
the old file is read by seek, the output written to a temp file, so memory
stays small even for files near 1 GiB. Every result is checked against the
target SHA-256 by the caller; a damaged patch fails with ValueError.
"""
import hashlib
import lzma
import os
import struct
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

MAGIC = b'AZP1'
HEADER = struct.Struct('<4sQQQQ')
CHUNK = 1 << 20
MAX_FILE = 4 << 30  # Largest game file a patch may produce.
_MASKS = {}


def masks(n):
    """Per-byte masks for n bytes: low 7 bits and the top bit of every byte."""
    pair = _MASKS.get(n)
    if pair is None:
        pair = (int.from_bytes(b'\x7f' * n, 'little'), int.from_bytes(b'\x80' * n, 'little'))
        if n == CHUNK or len(_MASKS) < 8:
            _MASKS[n] = pair
    return pair


def add_bytes(old, diff):
    """Byte-wise wrapping addition of two equal-length byte strings (SWAR on one big integer)."""
    n = len(old)
    if not n:
        return b''
    low, top = masks(n)
    a, b = int.from_bytes(old, 'little'), int.from_bytes(diff, 'little')
    return (((a & low) + (b & low)) ^ ((a ^ b) & top)).to_bytes(n, 'little')


class XzStream:
    """Exact reads from one in-memory xz stream, decompressed piece by piece."""

    def __init__(self, data):
        self.data, self.pos = memoryview(data), 0
        self.inflater = lzma.LZMADecompressor(format=lzma.FORMAT_XZ)

    def read(self, n):
        out = bytearray()
        while len(out) < n:
            if self.inflater.eof:
                raise ValueError('Game patch stream ends early')
            if self.inflater.needs_input:
                if self.pos >= len(self.data):
                    raise ValueError('Game patch stream is truncated')
                piece = self.data[self.pos:self.pos + CHUNK]
                self.pos += len(piece)
            else:
                piece = b''
            out += self.inflater.decompress(piece, max_length=n - len(out))
        return bytes(out)

    def finished(self):
        """True if the stream holds nothing beyond what was read."""
        if not self.inflater.eof:
            rest = self.inflater.decompress(self.data[self.pos:], max_length=1)
            self.pos = len(self.data)
            if rest or not self.inflater.eof:
                return False
        return not self.inflater.unused_data


def apply(old_path, patch_path, out_path, progress=None):
    """Write the new file from old + patch; returns its SHA-256. Raises ValueError on a damaged patch."""
    try:
        return _apply(old_path, patch_path, out_path, progress)
    except (lzma.LZMAError, EOFError, struct.error) as error:
        raise ValueError(f'Game patch is damaged ({error})') from error


def _apply(old_path, patch_path, out_path, progress):
    data = Path(patch_path).read_bytes()
    if len(data) < HEADER.size:
        raise ValueError('Game patch is truncated')
    magic, new_size, *lengths = HEADER.unpack_from(data)
    if magic != MAGIC or new_size > MAX_FILE or HEADER.size + sum(lengths) != len(data):
        raise ValueError('Game patch header is invalid')
    offset, streams = HEADER.size, []
    for length in lengths:
        streams.append(XzStream(data[offset:offset + length]))
        offset += length
    ctrl, diff, extra = streams
    digest = hashlib.sha256()
    old_size = os.path.getsize(old_path)
    written, old_pos = 0, 0
    with open(old_path, 'rb') as old, open(out_path, 'wb') as out:
        while written < new_size:
            add_len, extra_len, seek = struct.unpack('<qqq', ctrl.read(24))
            if add_len < 0 or extra_len < 0 or written + add_len + extra_len > new_size:
                raise ValueError('Game patch control is invalid')
            if old_pos < 0 or old_pos + add_len > old_size:
                raise ValueError('Game patch reads outside the old file')
            old.seek(old_pos)
            left = add_len
            while left:
                n = min(left, CHUNK)
                piece = add_bytes(old.read(n), diff.read(n))
                out.write(piece)
                digest.update(piece)
                left -= n
            left = extra_len
            while left:
                piece = extra.read(min(left, CHUNK))
                out.write(piece)
                digest.update(piece)
                left -= len(piece)
            written += add_len + extra_len
            old_pos += add_len + seek
            if progress:
                progress(written, new_size)
    if not (ctrl.finished() and diff.finished() and extra.finished()):
        raise ValueError('Game patch has data beyond the new file')
    return digest.hexdigest()


def unpack_full(asset_path, out_path, size):
    """Decompress a full asset (xz) in pieces; returns its SHA-256. Raises ValueError if damaged."""
    try:
        return _unpack_full(asset_path, out_path, size)
    except (lzma.LZMAError, EOFError) as error:
        raise ValueError(f'Game file asset is damaged ({error})') from error


def _unpack_full(asset_path, out_path, size):
    digest = hashlib.sha256()
    inflater = lzma.LZMADecompressor(format=lzma.FORMAT_XZ)
    written = 0
    with open(asset_path, 'rb') as source, open(out_path, 'wb') as out:
        while not inflater.eof:
            piece = source.read(CHUNK) if inflater.needs_input else b''
            if inflater.needs_input and not piece:
                raise ValueError('Game file asset is truncated')
            chunk = inflater.decompress(piece, max_length=CHUNK)
            written += len(chunk)
            if written > size:
                raise ValueError('Game file asset unpacks larger than signed')
            out.write(chunk)
            digest.update(chunk)
        if inflater.unused_data or source.read(1):
            raise ValueError('Game file asset has data after its end')
    return digest.hexdigest()


# ------------------------------------------------------------------ our side

def _compress_file(source, target, preset):
    compressor = lzma.LZMACompressor(format=lzma.FORMAT_XZ, check=lzma.CHECK_CRC64, preset=preset)
    with open(source, 'rb') as inp, open(target, 'wb') as out:
        while True:
            piece = inp.read(16 * CHUNK)
            if not piece:
                break
            out.write(compressor.compress(piece))
        out.write(compressor.flush())


def pack(prefix, new_size, target, preset=9 | lzma.PRESET_EXTREME):
    """Compress the three raw streams of azpatch-gen (in parallel; lzma releases the GIL) into one AZP1 file."""
    raw = [Path(f'{prefix}.{name}') for name in ('ctrl', 'diff', 'extra')]
    packed = [Path(f'{prefix}.{name}.xz') for name in ('ctrl', 'diff', 'extra')]
    with ThreadPoolExecutor(3) as pool:
        list(pool.map(lambda pair: _compress_file(*pair, preset), zip(raw, packed)))
    with open(target, 'wb') as out:
        out.write(HEADER.pack(MAGIC, new_size, *(p.stat().st_size for p in packed)))
        for p in packed:
            with open(p, 'rb') as inp:
                while piece := inp.read(16 * CHUNK):
                    out.write(piece)
    for p in raw + packed:
        p.unlink()


def pack_full(source, target, preset=9 | lzma.PRESET_EXTREME):
    _compress_file(source, target, preset)

